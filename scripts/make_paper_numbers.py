"""Export analysis results into LaTeX macros and tables for the manuscript.

Every number quoted in paper/sections/*.tex should come from paper/generated/*.tex.
Usage: python scripts/make_paper_numbers.py --root results/v11/confirmation --prefix c
"""
import argparse
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / 'paper' / 'generated'
TASKS = ['early', 'late', 'dms']
OPTS = ['adam', 'rms']
TASK_TEX = {'early': 'Early', 'late': 'Late', 'dms': 'Dms'}
OPT_TEX = {'adam': 'Adam', 'rms': 'Rms'}


def macro(name, value):
    name = re.sub(r'[^A-Za-z]', '', name)
    return f'\\newcommand{{\\{name}}}{{{value}}}\n'


def fmt_p(p):
    if p is None or not np.isfinite(p):
        return 'n.e.'
    if p < 1e-4:
        return '<10^{-4}'
    if p < .001:
        return f'{p:.4f}'
    return f'{p:.3f}'


def lr_table():
    rows = []
    final = ROOT / 'results' / 'v11' / 'tune' / 'final_selection.json'
    if not final.exists():
        return
    allsel = json.loads(final.read_text())
    for task in TASKS:
        for opt in OPTS:
            for learner, r in allsel.get(f'{task}_{opt}', {}).items():
                rows.append((task, opt, learner, r['lr_rec'], r['lr_out']))
    lines = ['\\begin{table}[h]\\centering\\small',
             '\\caption{Learning rates selected on the development cohort by validation BCE '
             '(recurrent / readout). The frozen reservoir has no recurrent rate.}\\label{tab:lr}',
             '\\begin{tabular}{llcccc}\\toprule',
             'task & optimizer & BPTT & local & local (no $\\beta$) & reservoir\\\\ \\midrule']
    for task in TASKS:
        for opt in OPTS:
            sel = {r[2]: r for r in rows if r[0] == task and r[1] == opt}
            if not sel:
                continue
            cell = lambda l: (f'{sel[l][3]:g} / {sel[l][4]:g}' if l != 'readout_only' else f'-- / {sel[l][4]:g}') if l in sel else '--'
            lines.append(f'{task} & {opt} & ' + ' & '.join(cell(l) for l in ['bptt', 'local', 'local_no_beta', 'readout_only']) + '\\\\')
    lines += ['\\bottomrule\\end{tabular}\\end{table}']
    (GEN / 'lr_table.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')


def lock_table():
    lock = ROOT / 'docs' / 'LOCK_v11.json'
    if not lock.exists():
        return
    d = json.loads(lock.read_text())
    lines = ['\\begin{table}[h]\\centering\\small\\caption{Protocol lock record.}\\label{tab:lock}',
             '\\begin{tabular}{ll}\\toprule']
    for k in ['locked_at_utc', 'protocol_sha256', 'source_hash', 'analysis_sha256', 'confirmation_configs_sha256']:
        if k in d:
            v = str(d[k])
            lines.append(f'{k.replace("_", " ")} & \\texttt{{{v[:32]}{"..." if len(v) > 32 else ""}}}\\\\')
    lines += ['\\bottomrule\\end{tabular}\\end{table}']
    (GEN / 'lock_table.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')


def numbers(root, prefix):
    tests = json.loads((root / 'analysis' / 'confirmatory_tests.json').read_text())
    out = ['% generated by scripts/make_paper_numbers.py; do not edit\n']
    for r in tests['family_A']:
        if r.get('status') != 'ok':
            continue
        key = {'A1': 'AOne', 'A2': 'ATwo', 'A3': 'AThree'}[r['contrast'][:2]] + TASK_TEX[r['task']] + OPT_TEX[r['optimizer']]
        out.append(macro(key + 'Diff', f"{r['diff_pp']:.1f}"))
        out.append(macro(key + 'CI', f"[{r['ci95_low']:.1f}, {r['ci95_high']:.1f}]"))
        out.append(macro(key + 'P', fmt_p(r['p_holm'])))
        out.append(macro(key + 'Wins', f"{r['wins_a']}/{r['n']}"))
    cond = pd.DataFrame(tests['conditions'])
    for _, r in cond.iterrows():
        name = 'M' + TASK_TEX.get(r.task, r.task) + OPT_TEX.get(r.optimizer, r.optimizer) + r.condition.title().replace('_', '')
        out.append(macro(name, f"{r['test_delay/accuracy_incongruent']:.1f}"))
        out.append(macro(name + 'Id', f"{r['test_id/accuracy']:.1f}"))
        out.append(macro(name + 'Rate', f"{r['rate_hz']:.1f}"))
    for r in tests['family_B']:
        if r.get('status') != 'ok' or r.get('family') == 'descriptive':
            continue
        term = r['contrast'].replace('B factorial: ', 'Fac').replace('B homogeneity (bptt): intact - homog', 'HomBptt') \
            .replace('B homogeneity (local): intact - homog', 'HomLocal').replace(' x ', 'X')
        key = 'B' + term + TASK_TEX[r['task']] + OPT_TEX[r['optimizer']]
        out.append(macro(key + 'Diff', f"{r['diff_pp']:.1f}"))
        out.append(macro(key + 'CI', f"[{r['ci95_low']:.1f}, {r['ci95_high']:.1f}]"))
        out.append(macro(key + 'P', fmt_p(r.get('p_holm'))))
        out.append(macro(key + 'Eq', r.get('equivalence_5pp', '').replace('_', ' ')))
    for r in tests['family_C']:
        if r.get('status') != 'ok':
            continue
        key = 'C' + re.sub(r'[^A-Za-z]', '', r['contrast'].title()) + TASK_TEX[r['task']]
        out.append(macro(key + 'Diff', f"{r['diff_pp']:.1f}"))
        out.append(macro(key + 'CI', f"[{r['ci95_low']:.1f}, {r['ci95_high']:.1f}]"))
        out.append(macro(key + 'P', fmt_p(r['p_value'])))
    seen, uniq = set(), []
    for line in out:
        name = line.split('}')[0]
        if name not in seen:
            seen.add(name)
            uniq.append(line)
    (GEN / 'numbers.tex').write_text(''.join(uniq), encoding='utf-8')
    print(f'{len(uniq)} macros -> {GEN / "numbers.tex"}')


TASK_NAME = {'early': 'T1-early', 'late': 'T1-late', 'dms': 'T2-dms'}


def _cell(r, key='p_holm'):
    p = r.get(key)
    star = ''
    if p is not None and np.isfinite(p):
        star = r'$^{***}$' if p < .001 else r'$^{**}$' if p < .01 else r'$^{*}$' if p < .05 else ''
    return f"{r['diff_pp']:+.1f} [{r['ci95_low']:.1f}, {r['ci95_high']:.1f}]{star}"


def tables(root):
    tests = json.loads((root / 'analysis' / 'confirmatory_tests.json').read_text())
    A = pd.DataFrame(tests['family_A'])
    lines = [r'\begin{table}[t]\centering\small',
             r'\caption{Family A (confirmation cohort, 16 paired networks). Difference in unseen-delay '
             r'conflict accuracy (pp) with 95\% bootstrap CI; stars mark Holm-adjusted significance over all 18 '
             r'tests ($^*p<.05$, $^{**}p<.01$, $^{***}p<.001$).}\label{tab:familyA}',
             r'\begin{tabular}{llccc}\toprule',
             r'task & optimizer & A1: local $-$ no $\beta$ & A2: local $-$ reservoir & A3: BPTT $-$ local\\ \midrule']
    for task in TASKS:
        for opt in OPTS:
            f = A[(A.task == task) & (A.optimizer == opt)]
            cells = [_cell(f[f.contrast.str.startswith(k)].iloc[0]) for k in ('A1', 'A2', 'A3')]
            lines.append(f"{TASK_NAME[task]} & {'Adam' if opt == 'adam' else 'RMS'} & " + ' & '.join(cells) + r'\\')
    lines += [r'\bottomrule\end{tabular}\end{table}']
    (GEN / 'familyA_table.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    B = pd.DataFrame(tests['family_B'])
    terms = [('B factorial: identity', 'identity'), ('B factorial: topology', 'wiring'),
             ('B homogeneity (bptt): intact - homog', r'heterog., BPTT'),
             ('B homogeneity (local): intact - homog', r'heterog., local')]
    lines = [r'\begin{table}[t]\centering\footnotesize',
             r'\caption{Family B. Identity: intact $-$ within-type shuffle (matched); wiring: type prior $-$ '
             r'degree-preserving rewiring (factorial main effects, averaged over learner and the other factor); '
             r'heterogeneity: intact $-$ type-mean cells, for each learner. pp with 95\% CI; stars: Holm within each '
             r'task/optimizer family of 9. N: practically negligible (90\% CI within $\pm$5\,pp); I: inconclusive; '
             r'D: different.}\label{tab:familyB}',
             r'\begin{tabular}{ll' + 'c' * len(terms) + r'}\toprule',
             r'task & opt. & ' + ' & '.join(t[1] for t in terms) + r'\\ \midrule']
    code = {'practically_negligible': 'N', 'inconclusive': 'I', 'different': 'D'}
    for task in TASKS:
        for opt in OPTS:
            f = B[(B.task == task) & (B.optimizer == opt)]
            cells = []
            for term, _ in terms:
                r = f[f.contrast == term].iloc[0]
                cells.append(_cell(r) + ' ' + code.get(r.get('equivalence_5pp'), ''))
            lines.append(f"{TASK_NAME[task]} & {'Adam' if opt == 'adam' else 'RMS'} & " + ' & '.join(cells) + r'\\')
    lines += [r'\bottomrule\end{tabular}\end{table}']
    (GEN / 'familyB_table.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('tables written')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', type=Path)
    ap.add_argument('--prefix')
    a = ap.parse_args()
    GEN.mkdir(parents=True, exist_ok=True)
    lr_table()
    lock_table()
    if a.root:
        numbers(a.root, a.prefix)
        tables(a.root)
